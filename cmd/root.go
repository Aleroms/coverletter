// rootCmd represents the base command when called without any subcommands
var rootCmd = &cobra.Command{
	Use:   "coverLetter",
	Short: "generates a personalized cover letter based on user's provided resume and job description",
	Long: `creates a tailored cover letter by taking inputs such as the company name,
	position, and optional other details.`,
}

// Execute adds all child commands to the root command and sets flags appropriately.
// This is called by main.main(). It only needs to happen once to the rootCmd.
func Execute() {
	err := rootCmd.Execute()
	if err != nil {
		os.Exit(1)
	}
}

